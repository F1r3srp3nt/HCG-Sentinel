#!/usr/bin/env python3
"""Generates SentinelCore/Tests/SentinelCoreTests/SecurityLabFixtures.swift.

Every fixture is synthetic. Credential-like strings are assembled from pieces so that no complete
vendor-format token appears in this repository, and none of them is valid anywhere.

    python3 Tools/make_security_fixtures.py > SentinelCore/Tests/SentinelCoreTests/SecurityLabFixtures.swift
"""
import base64
import io
import struct
import tarfile
import time
import zipfile
import zlib

FIXED_TIME = (2026, 1, 1, 0, 0, 0)
GENERIC_SECRET_LINE = "DB_PASSWORD=" + "Xk9vR2mQ" + "7tLp4wZs\n"


def raw_deflate(data: bytes, level: int = 9) -> bytes:
    compressor = zlib.compressobj(level, zlib.DEFLATED, -15)
    return compressor.compress(data) + compressor.flush()


def dynamic_text() -> bytes:
    return "".join(f"line {i}: the quick brown fox jumps over the lazy dog\n" for i in range(200)).encode()


def zip_info(name: str, mode: int = 0o100644) -> zipfile.ZipInfo:
    info = zipfile.ZipInfo(name, FIXED_TIME)
    info.create_system = 3
    info.external_attr = mode << 16
    info.compress_type = zipfile.ZIP_DEFLATED
    return info


def mixed_zip() -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        archive.writestr(zip_info("config/app.env"), "# synthetic fixture\n" + GENERIC_SECRET_LINE)
        archive.writestr(zip_info("README.md"), "Nothing secret here.\n" * 20)
        archive.writestr(zip_info("../../outside.txt"), "escapes the folder\n")
        archive.writestr(zip_info("link-to-etc", 0o120777), "/etc/passwd")
        archive.writestr(zip_info("inner.zip"), b"PK\x03\x04not really")
        archive.writestr(zip_info("logo.bin"), bytes(range(256)) * 4)
    return buffer.getvalue()


def bomb_zip() -> bytes:
    """One entry of 4 MiB of zeros whose declared size is forged to 100 bytes."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        archive.writestr(zip_info("zeros.txt"), b"\0" * (4 * 1024 * 1024))
    data = bytearray(buffer.getvalue())
    central = data.rfind(b"PK\x01\x02")
    struct.pack_into("<I", data, central + 24, 100)
    local = data.find(b"PK\x03\x04")
    struct.pack_into("<I", data, local + 22, 100)
    return bytes(data)


def encrypted_flag_zip() -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        archive.writestr(zip_info("secret.txt"), "pretend this is encrypted\n")
    data = bytearray(buffer.getvalue())
    for signature, flag_offset in ((b"PK\x01\x02", 8), (b"PK\x03\x04", 6)):
        index = data.find(signature)
        flags = struct.unpack_from("<H", data, index + flag_offset)[0]
        struct.pack_into("<H", data, index + flag_offset, flags | 1)
    return bytes(data)


def tar_gz() -> bytes:
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w:gz", format=tarfile.USTAR_FORMAT) as archive:
        def add(name: str, content: bytes = b"", kind=tarfile.REGTYPE, link: str = ""):
            info = tarfile.TarInfo(name)
            info.mtime = 1767225600
            info.type = kind
            info.linkname = link
            info.size = len(content) if kind == tarfile.REGTYPE else 0
            archive.addfile(info, io.BytesIO(content) if kind == tarfile.REGTYPE else None)
        add("project/settings.ini", ("[db]\n" + GENERIC_SECRET_LINE).encode())
        add("project/notes.txt", b"plain notes\n")
        add("project/link", kind=tarfile.SYMTYPE, link="/etc/shadow")
        add("/abs/path.txt", b"absolute\n")
    return buffer.getvalue()


def swift_literal(name: str, data: bytes, comment: str) -> str:
    encoded = base64.b64encode(data).decode()
    chunks = [encoded[i:i + 100] for i in range(0, len(encoded), 100)]
    body = "\n".join(f'        "{chunk}"' for chunk in chunks)
    joined = " +\n".join(body.split("\n"))
    return f"    /// {comment}\n    static let {name} = bytes(\n{joined}\n    )\n"


def main():
    fixtures = [
        ("dynamicDeflate", raw_deflate(dynamic_text()), "Raw DEFLATE (dynamic Huffman) of `dynamicText`."),
        ("fixedDeflate", raw_deflate(b"hello hello hello sentinel", 1), "Raw DEFLATE (fixed Huffman) of \"hello hello hello sentinel\"."),
        ("storedDeflate", raw_deflate(b"stored block", 0), "Raw DEFLATE (stored block) of \"stored block\"."),
        ("mixedZip", mixed_zip(), "Zip: a generic credential, a README, a zip-slip entry, a symlink, a nested zip and a binary file."),
        ("bombZip", bomb_zip(), "Zip: 4 MiB of zeros with the declared size forged to 100 bytes."),
        ("encryptedZip", encrypted_flag_zip(), "Zip whose only entry has the encryption flag set."),
        ("tarGz", tar_gz(), "tar.gz: a credential in settings.ini, a symlink and an absolute path."),
    ]
    print("// Generated by Tools/make_security_fixtures.py. Do not edit by hand. All data is synthetic.")
    print("import Foundation\n")
    print("enum SecurityLabFixtures {")
    print("    static func bytes(_ base64: String) -> [UInt8] { [UInt8](Data(base64Encoded: base64)!) }\n")
    print('    static let dynamicText: String = (0..<200).map { "line \\($0): the quick brown fox jumps over the lazy dog\\n" }.joined()\n')
    for name, data, comment in fixtures:
        print(swift_literal(name, data, comment))
    print("}")


if __name__ == "__main__":
    main()
