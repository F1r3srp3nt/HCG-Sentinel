import Foundation

public enum HTTPMethod: String, CaseIterable, Codable, Equatable {
    case GET, HEAD, POST, PUT, PATCH, DELETE, OPTIONS

    public var allowsBody: Bool { self != .GET && self != .HEAD }
}

public struct HeaderField: Identifiable, Equatable, Codable {
    public var id: UUID
    public var name: String
    public var value: String
    public var isEnabled: Bool

    public init(id: UUID = UUID(), name: String, value: String, isEnabled: Bool = true) {
        self.id = id
        self.name = name
        self.value = value
        self.isEnabled = isEnabled
    }
}

/// An editable request generated by Sentinel itself.
public struct RequestDraft: Equatable, Codable {
    public var method: HTTPMethod
    /// Path and optional query, relative to the selected test endpoint.
    public var path: String
    public var headers: [HeaderField]
    public var body: String

    public init(method: HTTPMethod = .GET, path: String = "/", headers: [HeaderField] = [], body: String = "") {
        self.method = method
        self.path = path
        self.headers = headers
        self.body = body
    }

    public static let template = RequestDraft(
        method: .GET, path: "/",
        headers: [HeaderField(name: "Accept", value: "*/*"),
                  HeaderField(name: "User-Agent", value: "HCG-Sentinel/1.0 (request composer)")],
        body: "")
}

public enum RequestValidationError: Error, Equatable {
    case noEndpoint
    case invalidEndpoint(String)
    case invalidPath
    case offEndpoint
    case invalidHeaderName(String)
    case invalidHeaderValue(String)
    case managedHeader(String)
    case bodyNotAllowed(String)
    case bodyTooLarge(Int)

    public var userMessage: String {
        switch self {
        case .noEndpoint: return "Select an HCG test endpoint in Settings before sending."
        case .invalidEndpoint(let reason): return "The test endpoint is not valid: \(reason)"
        case .invalidPath: return "The path must start with “/” and contain no spaces or control characters."
        case .offEndpoint: return "The request would leave the selected test endpoint, so it was not sent."
        case .invalidHeaderName(let name): return "“\(name)” is not a valid header name."
        case .invalidHeaderValue(let name): return "The value of “\(name)” contains a line break."
        case .managedHeader(let name): return "“\(name)” is set by the system networking stack and cannot be edited."
        case .bodyNotAllowed(let method): return "\(method) requests are sent without a body. Clear the body or change the method."
        case .bodyTooLarge(let limit): return "The body is larger than \(limit) bytes."
        }
    }
}

/// The single, explicitly selected service that the composer may contact.
public struct TestEndpoint: Equatable {
    public let baseURL: URL
    public let scheme: String
    public let host: String
    public let port: Int

    public init(string: String) throws {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { throw RequestValidationError.noEndpoint }
        guard let components = URLComponents(string: trimmed), let scheme = components.scheme?.lowercased(),
              scheme == "http" || scheme == "https" else {
            throw RequestValidationError.invalidEndpoint("use an http:// or https:// URL")
        }
        guard let host = components.host?.lowercased(), !host.isEmpty else {
            throw RequestValidationError.invalidEndpoint("a host name or address is required")
        }
        guard components.user == nil, components.password == nil else {
            throw RequestValidationError.invalidEndpoint("put credentials in a header, not in the URL")
        }
        guard components.query == nil, components.fragment == nil else {
            throw RequestValidationError.invalidEndpoint("remove the query string or fragment; add them to the request path")
        }
        guard components.path.isEmpty || components.path == "/" else {
            throw RequestValidationError.invalidEndpoint("enter only scheme, host and port; the path belongs to the request")
        }
        var base = URLComponents()
        base.scheme = scheme
        base.host = components.host
        base.port = components.port
        guard let url = base.url else { throw RequestValidationError.invalidEndpoint("could not be parsed") }
        self.baseURL = url
        self.scheme = scheme
        self.host = host
        self.port = components.port ?? (scheme == "https" ? 443 : 80)
    }

    public var displayString: String { baseURL.absoluteString }

    public func contains(_ url: URL) -> Bool {
        guard let components = URLComponents(url: url, resolvingAgainstBaseURL: true),
              let scheme = components.scheme?.lowercased(), let host = components.host?.lowercased() else { return false }
        let port = components.port ?? (scheme == "https" ? 443 : 80)
        return scheme == self.scheme && host == self.host && port == self.port
            && components.user == nil && components.password == nil
    }
}

/// A fully validated request, ready for a transport.
public struct PreparedRequest: Equatable {
    public struct Header: Equatable {
        public let name: String
        public let value: String
    }

    public let method: HTTPMethod
    public let url: URL
    public let headers: [Header]
    public let body: Data?
}

public enum RequestBuilder {
    public static let maxBodyBytes = 1_048_576
    private static let managedHeaders: Set<String> = ["host", "content-length", "connection", "transfer-encoding",
                                                      "proxy-connection", "upgrade", "te", "keep-alive"]
    private static let tokenCharacters = CharacterSet(charactersIn:
        "!#$%&'*+-.^_`|~0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ")

    public static func prepare(_ draft: RequestDraft, endpoint: TestEndpoint?) throws -> PreparedRequest {
        guard let endpoint = endpoint else { throw RequestValidationError.noEndpoint }
        let path = draft.path.trimmingCharacters(in: .whitespacesAndNewlines)
        guard path.hasPrefix("/"), !path.hasPrefix("//"),
              !path.unicodeScalars.contains(where: { $0.value <= 0x20 || $0.value == 0x7f || $0 == "\\" }),
              let url = URL(string: endpoint.baseURL.absoluteString + path) else {
            throw RequestValidationError.invalidPath
        }
        guard endpoint.contains(url) else { throw RequestValidationError.offEndpoint }

        var headers: [PreparedRequest.Header] = []
        for field in draft.headers where field.isEnabled {
            let name = field.name.trimmingCharacters(in: .whitespaces)
            if name.isEmpty && field.value.isEmpty { continue }
            guard !name.isEmpty, name.unicodeScalars.allSatisfy({ tokenCharacters.contains($0) }) else {
                throw RequestValidationError.invalidHeaderName(field.name)
            }
            guard !managedHeaders.contains(name.lowercased()) else { throw RequestValidationError.managedHeader(name) }
            guard !field.value.unicodeScalars.contains(where: { $0 == "\r" || $0 == "\n" || $0.value == 0 }) else {
                throw RequestValidationError.invalidHeaderValue(name)
            }
            headers.append(PreparedRequest.Header(name: name, value: field.value.trimmingCharacters(in: .whitespaces)))
        }

        var body: Data?
        if !draft.body.isEmpty {
            guard draft.method.allowsBody else { throw RequestValidationError.bodyNotAllowed(draft.method.rawValue) }
            let data = Data(draft.body.utf8)
            guard data.count <= maxBodyBytes else { throw RequestValidationError.bodyTooLarge(maxBodyBytes) }
            body = data
        }
        return PreparedRequest(method: draft.method, url: url, headers: headers, body: body)
    }
}

public struct RequestChange: Equatable, Identifiable {
    public enum Kind: String, Equatable {
        case method, path, headerAdded, headerRemoved, headerChanged, body
    }

    public let kind: Kind
    public let subject: String
    public let before: String?
    public let after: String?

    public var id: String { "\(kind.rawValue):\(subject)" }

    public var title: String {
        switch kind {
        case .method: return "Method changed"
        case .path: return "Path changed"
        case .headerAdded: return "Header added: \(subject)"
        case .headerRemoved: return "Header removed: \(subject)"
        case .headerChanged: return "Header changed: \(subject)"
        case .body: return "Body changed"
        }
    }
}

public enum RequestPreview {
    /// Differences between the starting template and the edited draft.
    public static func changes(from baseline: RequestDraft, to draft: RequestDraft) -> [RequestChange] {
        var changes: [RequestChange] = []
        if baseline.method != draft.method {
            changes.append(RequestChange(kind: .method, subject: "method", before: baseline.method.rawValue, after: draft.method.rawValue))
        }
        if baseline.path != draft.path {
            changes.append(RequestChange(kind: .path, subject: "path", before: baseline.path, after: draft.path))
        }
        let before = effectiveHeaders(baseline), after = effectiveHeaders(draft)
        for (key, old) in before.sorted(by: { $0.key < $1.key }) {
            if let new = after[key] {
                if new.value != old.value {
                    changes.append(RequestChange(kind: .headerChanged, subject: new.name, before: old.value, after: new.value))
                }
            } else {
                changes.append(RequestChange(kind: .headerRemoved, subject: old.name, before: old.value, after: nil))
            }
        }
        for (key, new) in after.sorted(by: { $0.key < $1.key }) where before[key] == nil {
            changes.append(RequestChange(kind: .headerAdded, subject: new.name, before: nil, after: new.value))
        }
        if baseline.body != draft.body {
            changes.append(RequestChange(kind: .body, subject: "body",
                                         before: "\(baseline.body.utf8.count) bytes", after: "\(draft.body.utf8.count) bytes"))
        }
        return changes
    }

    private static func effectiveHeaders(_ draft: RequestDraft) -> [String: (name: String, value: String)] {
        var result: [String: (name: String, value: String)] = [:]
        for field in draft.headers where field.isEnabled && !field.name.isEmpty {
            result[field.name.lowercased()] = (field.name, field.value)
        }
        return result
    }

    /// HTTP/1.1-style rendering of what will be handed to the networking stack.
    /// The system adds Host, Content-Length and connection headers itself.
    public static func rawText(_ request: PreparedRequest, redactor: Redactor? = nil) -> String {
        var target = request.url.path.isEmpty ? "/" : request.url.path
        if let components = URLComponents(url: request.url, resolvingAgainstBaseURL: false),
           let encodedPath = Optional(components.percentEncodedPath), !encodedPath.isEmpty {
            target = encodedPath
            if let query = components.percentEncodedQuery { target += "?" + query }
        }
        if let redactor = redactor { target = redactor.text(target) }
        var lines = ["\(request.method.rawValue) \(target) HTTP/1.1"]
        var hostLine = request.url.host ?? ""
        if let port = request.url.port { hostLine += ":\(port)" }
        lines.append("Host: \(hostLine)")
        for header in request.headers {
            let value = redactor?.headerValue(name: header.name, value: header.value) ?? header.value
            lines.append("\(header.name): \(value)")
        }
        var text = lines.joined(separator: "\n") + "\n"
        if let body = request.body, !body.isEmpty {
            let bodyText = String(data: body, encoding: .utf8) ?? "<\(body.count) bytes of binary data>"
            text += "\n" + (redactor?.text(bodyText) ?? bodyText)
        }
        return text
    }
}
